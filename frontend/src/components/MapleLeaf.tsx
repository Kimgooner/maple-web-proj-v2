/**
 * 추이 선 끝에 놓는 단풍잎.
 *
 * <p>"지금 여기까지 왔다"는 표시다. 선이 끝나는 자리라 눈이 마지막으로 닿는 곳이고,
 * 서비스 이름이 MapleDelta 라 잎 하나가 분위기를 만든다.
 *
 * <p>버섯·슬라임 대신 잎을 고른 이유는, 그것들이 넥슨이 그린 캐릭터라서다. 비슷하게 그려도
 * 넥슨 저작물을 모방한 것이 되고 약관 제6조가 허락한 범위 안에서만 쓰라고 한다. 단풍잎은
 * 특정 디자인이 아니라 자연물이라 직접 그리면 온전히 우리 것이다.
 *
 * <p>좌표는 16을 축으로 좌우 대칭이다. 꼭짓점 하나, 양옆으로 잎맥 둘씩, 아래에 잎자루.
 */
export function MapleLeaf({ x, y, size = 15 }: { x: number; y: number; size?: number }) {
  return (
    <g transform={`translate(${x - size / 2} ${y - size / 2}) scale(${size / 32})`}>
      <path
        className="maple-leaf"
        d="M16 2.5 17.6 8 21.2 5.6 20.4 11 25.6 9.2 24 13.4 29.5 14 21.5 20
           22.6 23 17 22.2 17 29.5 15 29.5 15 22.2 9.4 23 10.5 20 2.5 14
           8 13.4 6.4 9.2 11.6 11 10.8 5.6 14.4 8Z"
      />
    </g>
  );
}
