    private WeaponAddOptionTable() {
    }

    public static Integer findStage(String weaponFamily, String weaponType, Integer addOption) {
        if (weaponFamily == null || weaponType == null || addOption == null || addOption <= 0) {
            return null;
        }

        List<Integer> stages = findStages(weaponFamily, weaponType);
        if (stages == null) {
            return null;
        }
        for (int index = 0; index < stages.size(); index++) {
            if (stages.get(index).intValue() == addOption.intValue()) {
                return index + 1;
            }
        }
        return null;
    }

    public static Integer bowAddOption(String weaponFamily, Integer stage) {
        if (weaponFamily == null || stage == null) {
            return 0;
        }

        List<Integer> bowStages = findStages(weaponFamily, BOW_TYPE);
        if (bowStages == null || stage < 1 || stage > bowStages.size()) {
            return 0;
        }
        return bowStages.get(stage - 1);
    }

    private static List<Integer> findStages(String weaponFamily, String weaponType) {
        Map<String, List<Integer>> family = PROFILES.get(weaponFamily);
        if (family == null) {
            return null;
        }

        String normalizedType = normalize(weaponType);
        for (Map.Entry<String, List<Integer>> entry : family.entrySet()) {
            String key = normalize(entry.getKey());
            if (normalizedType.equals(key)) {
                return entry.getValue();
            }
        }
        return null;
    }

    private static String normalize(String value) {
        return value == null ? "" : value.replace(" ", "").trim();
    }

    private static Map<String, List<Integer>> profiles(Object... values) {
        Map<String, List<Integer>> profiles = new LinkedHashMap<>();
        for (int index = 0; index < values.length; index += 6) {
            String weaponType = (String) values[index];
            int stage1 = (Integer) values[index + 1];
            int stage2 = (Integer) values[index + 2];
            int stage3 = (Integer) values[index + 3];
            int stage4 = (Integer) values[index + 4];
            int stage5 = (Integer) values[index + 5];
            profiles.put(weaponType, List.of(stage1, stage2, stage3, stage4, stage5));
        }
        return Map.copyOf(profiles);
    }
